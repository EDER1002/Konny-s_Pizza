-- Extensión para la restricción que evita reservas cruzadas.
create schema if not exists extensions;
create extension if not exists btree_gist with schema extensions;


-- ---------------------------------------------------------------------
-- 1. Tablas (sección 10 del documento)
-- ---------------------------------------------------------------------

-- Mesas del restaurante.
create table public.mesas (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  zona        text not null,
  capacidad   integer not null,
  activa      boolean not null default true,
  foto_url    text,
  creado_en   timestamptz not null default now(),
  constraint mesas_nombre_check    check (char_length(btrim(nombre)) between 1 and 40),
  constraint mesas_zona_check      check (zona in ('terraza', 'salon')),
  constraint mesas_capacidad_check check (capacidad between 1 and 20)
);
-- No se repiten nombres de mesa ("Mesa 1" y "mesa 1" cuentan como iguales).
create unique index mesas_nombre_unico on public.mesas (lower(btrim(nombre)));

-- Horario de atención: una fila por día y jornada (almuerzo / noche).
create table public.horarios (
  id             bigint generated by default as identity primary key,
  dia_semana     text not null,
  jornada        text not null,
  hora_inicio    time not null,
  hora_fin       time not null,
  duracion_slot  integer not null default 60,
  activo         boolean not null default true,
  constraint horarios_dia_check      check (dia_semana in ('lunes','martes','miercoles','jueves','viernes','sabado','domingo')),
  constraint horarios_jornada_check  check (jornada in ('almuerzo', 'noche')),
  constraint horarios_duracion_check check (duracion_slot between 15 and 240),
  constraint horarios_horas_check    check (hora_fin > hora_inicio),
  constraint horarios_dia_jornada_unico unique (dia_semana, jornada)
);

-- Reservas de los clientes.
create table public.reservas (
  id                bigint generated by default as identity primary key,
  mesa_id           bigint not null references public.mesas (id) on delete restrict,
  cliente_nombre    text not null,
  cliente_contacto  text,
  num_personas      integer not null,
  fecha             date not null,
  hora_inicio       time not null,
  hora_fin          time not null,
  estado            text not null default 'confirmada',
  creado_en         timestamptz not null default now(),
  constraint reservas_nombre_check   check (char_length(btrim(cliente_nombre)) between 2 and 80),
  constraint reservas_contacto_check check (cliente_contacto is null or char_length(cliente_contacto) <= 40),
  constraint reservas_personas_check check (num_personas >= 1),
  constraint reservas_horas_check    check (hora_fin > hora_inicio),
  constraint reservas_estado_check   check (estado in ('confirmada', 'cancelada', 'completada')),
  -- Evita la doble reserva: dos reservas no canceladas de la misma mesa
  -- no pueden cruzarse en el tiempo. Lo revisa la base de datos, así que
  -- funciona aunque dos personas reserven en el mismo segundo.
  constraint reservas_sin_cruce exclude using gist (
    mesa_id with =,
    tsrange(fecha + hora_inicio, fecha + hora_fin, '[)') with &&
  ) where (estado <> 'cancelada')
);
create index reservas_fecha_idx on public.reservas (fecha, mesa_id);

-- Platos de la carta digital.
create table public.platos (
  id           bigint generated by default as identity primary key,
  nombre       text not null,
  categoria    text not null,
  descripcion  text,
  precio       integer not null,
  disponible   boolean not null default true,
  constraint platos_nombre_check    check (char_length(btrim(nombre)) between 1 and 80),
  constraint platos_categoria_check check (categoria in ('pizzas', 'entradas', 'postres', 'bebidas')),
  constraint platos_precio_check    check (precio >= 0)
);

-- Correos que pueden entrar al panel de administración.
create table public.administradores (
  email text primary key
);


-- ---------------------------------------------------------------------
-- 2. Funciones
-- ---------------------------------------------------------------------

-- Nombre del día en español (sin tildes), igual que en la tabla horarios.
create function public.dia_semana_es(p_fecha date) returns text
language sql immutable as $$
  select (array['lunes','martes','miercoles','jueves','viernes','sabado','domingo'])[extract(isodow from p_fecha)::int]
$$;

-- ¿El usuario que hace la consulta es administrador?
create function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.administradores a
    where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  )
$$;

-- Nunca deja guardar más personas que la capacidad de la mesa.
create function public.validar_capacidad() returns trigger
language plpgsql set search_path = public as $$
declare
  v_capacidad integer;
begin
  select capacidad into v_capacidad from public.mesas where id = new.mesa_id;
  if v_capacidad is not null and new.num_personas > v_capacidad then
    raise exception 'CAPACIDAD_EXCEDIDA'
      using detail = format('La mesa admite máximo %s personas.', v_capacidad);
  end if;
  return new;
end $$;

create trigger reservas_validar_capacidad
  before insert or update of mesa_id, num_personas on public.reservas
  for each row execute function public.validar_capacidad();

-- Slots ocupados de un día. Solo devuelve mesa y horas, nunca datos
-- personales, por eso el público puede usarla sin ver la tabla reservas.
create function public.obtener_ocupados(p_fecha date)
returns table (mesa_id bigint, hora_inicio text, hora_fin text)
language sql stable security definer set search_path = public as $$
  select r.mesa_id, to_char(r.hora_inicio, 'HH24:MI'), to_char(r.hora_fin, 'HH24:MI')
  from public.reservas r
  where r.fecha = p_fecha and r.estado <> 'cancelada'
  order by r.mesa_id, r.hora_inicio
$$;

-- Crea una reserva revisando todas las reglas en un solo paso.
-- Errores posibles: MESA_NO_DISPONIBLE, NOMBRE_INVALIDO, CONTACTO_INVALIDO,
-- PERSONAS_INVALIDAS, CAPACIDAD_EXCEDIDA, FECHA_INVALIDA, HORARIO_INVALIDO,
-- SLOT_OCUPADO.
create function public.crear_reserva(
  p_mesa_id          bigint,
  p_fecha            date,
  p_hora_inicio      time,
  p_cliente_nombre   text,
  p_num_personas     integer,
  p_cliente_contacto text default null
) returns json
language plpgsql security definer set search_path = public as $$
declare
  v_mesa      public.mesas;
  v_horario   public.horarios;
  v_hoy       date := (now() at time zone 'America/Bogota')::date;
  v_ahora     time := (now() at time zone 'America/Bogota')::time;
  v_nombre    text := btrim(coalesce(p_cliente_nombre, ''));
  v_contacto  text := nullif(btrim(coalesce(p_cliente_contacto, '')), '');
  v_minuto    integer;
  v_hora_fin  time;
  v_id        bigint;
begin
  select * into v_mesa from public.mesas where id = p_mesa_id;
  if not found or not v_mesa.activa then
    raise exception 'MESA_NO_DISPONIBLE';
  end if;

  if char_length(v_nombre) not between 2 and 80 then
    raise exception 'NOMBRE_INVALIDO';
  end if;
  if v_contacto is not null and char_length(v_contacto) > 40 then
    raise exception 'CONTACTO_INVALIDO';
  end if;
  if p_num_personas is null or p_num_personas < 1 then
    raise exception 'PERSONAS_INVALIDAS';
  end if;
  if p_num_personas > v_mesa.capacidad then
    raise exception 'CAPACIDAD_EXCEDIDA'
      using detail = format('La mesa admite máximo %s personas.', v_mesa.capacidad);
  end if;

  -- Solo desde hoy hasta 30 días, y nunca una hora que ya pasó.
  if p_fecha is null or p_fecha < v_hoy or p_fecha > v_hoy + 30
     or (p_fecha = v_hoy and p_hora_inicio <= v_ahora) then
    raise exception 'FECHA_INVALIDA';
  end if;

  -- La hora debe ser el inicio de un slot de una jornada activa de ese día.
  v_minuto := extract(epoch from p_hora_inicio)::integer / 60;
  select h.* into v_horario
  from public.horarios h
  where h.dia_semana = public.dia_semana_es(p_fecha)
    and h.activo
    and v_minuto >= extract(epoch from h.hora_inicio)::integer / 60
    and v_minuto + h.duracion_slot <= extract(epoch from h.hora_fin)::integer / 60
    and (v_minuto - extract(epoch from h.hora_inicio)::integer / 60) % h.duracion_slot = 0
  limit 1;
  if not found then
    raise exception 'HORARIO_INVALIDO';
  end if;

  v_hora_fin := p_hora_inicio + make_interval(mins => v_horario.duracion_slot);

  begin
    insert into public.reservas (mesa_id, cliente_nombre, cliente_contacto, num_personas, fecha, hora_inicio, hora_fin)
    values (p_mesa_id, v_nombre, v_contacto, p_num_personas, p_fecha, p_hora_inicio, v_hora_fin)
    returning id into v_id;
  exception when exclusion_violation then
    raise exception 'SLOT_OCUPADO';
  end;

  return json_build_object(
    'id',             v_id,
    'mesa_id',        v_mesa.id,
    'mesa_nombre',    v_mesa.nombre,
    'zona',           v_mesa.zona,
    'fecha',          to_char(p_fecha, 'YYYY-MM-DD'),
    'hora_inicio',    to_char(p_hora_inicio, 'HH24:MI'),
    'hora_fin',       to_char(v_hora_fin, 'HH24:MI'),
    'num_personas',   p_num_personas,
    'cliente_nombre', v_nombre
  );
end $$;


-- ---------------------------------------------------------------------
-- 3. Seguridad (Row Level Security)
--    Público: lee mesas, horarios y carta; reserva solo con crear_reserva.
--    Administrador: puede hacer todo.
-- ---------------------------------------------------------------------
alter table public.mesas           enable row level security;
alter table public.horarios        enable row level security;
alter table public.reservas        enable row level security;
alter table public.platos          enable row level security;
alter table public.administradores enable row level security;

create policy "Todos ven las mesas"        on public.mesas    for select to anon, authenticated using (true);
create policy "Todos ven los horarios"     on public.horarios for select to anon, authenticated using (true);
create policy "Todos ven la carta"         on public.platos   for select to anon, authenticated using (true);

create policy "El admin gestiona mesas"    on public.mesas    for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "El admin gestiona horarios" on public.horarios for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "El admin gestiona la carta" on public.platos   for all to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "El admin gestiona reservas" on public.reservas for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- La lista de administradores no se puede leer desde la app.
revoke all on table public.administradores from anon, authenticated;

revoke all on function public.crear_reserva(bigint, date, time, text, integer, text) from public;
revoke all on function public.obtener_ocupados(date) from public;
revoke all on function public.es_admin() from public;
grant execute on function public.crear_reserva(bigint, date, time, text, integer, text) to anon, authenticated;
grant execute on function public.obtener_ocupados(date) to anon, authenticated;
grant execute on function public.es_admin() to anon, authenticated;


-- ---------------------------------------------------------------------
-- 4. Tiempo real: avisa a la app cuando cambian estas tablas.
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.mesas, public.horarios, public.platos, public.reservas;
  end if;
end $$;


-- ---------------------------------------------------------------------
-- 5. Horario inicial: todos los días, 12:30-14:30 y 17:00-23:00,
--    reservas de 60 minutos. Se puede cambiar desde el panel admin.
-- ---------------------------------------------------------------------
insert into public.horarios (dia_semana, jornada, hora_inicio, hora_fin, duracion_slot)
select d.dia, j.jornada, j.inicio, j.fin, 60
from unnest(array['lunes','martes','miercoles','jueves','viernes','sabado','domingo']) with ordinality as d(dia, orden)
cross join (values ('almuerzo', time '12:30', time '14:30'),
                   ('noche',    time '17:00', time '23:00')) as j(jornada, inicio, fin)
order by d.orden, j.inicio;
